// Маркер авто-генерируемого скрипта. Пока он есть в файле — скрипт считается
// управляемым программой и перезаписывается из шаблона при его изменении (после
// обновления программы). Удалите строку-маркер — файл станет «кастомным» и больше
// никогда не будет перезаписан.
pub const GEN_MARKER: &str = "# ASWADPFTLS-GENERATED";

// Полный список ролей палитры — порядок неважен, используется в циклах генерации
// CSS-файлов (waybar, swaync, walker).
const ROLES: &str = "ROSEWATER FLAMINGO PINK MAUVE RED MAROON PEACH YELLOW GREEN \
TEAL SKY SAPPHIRE BLUE LAVENDER TEXT SUBTEXT1 SUBTEXT0 OVERLAY2 OVERLAY1 OVERLAY0 \
SURFACE2 SURFACE1 SURFACE0 BASE MANTLE CRUST";

pub fn script_template(name: &str, palette_path: &str) -> String {
	let header = format!(
		"#!/usr/bin/env fish\n\
         {GEN_MARKER} — авто-генерируется из шаблона, не редактировать.\n\
         # Чтобы кастомизировать: удалите строку-маркер выше (файл перестанет перезаписываться).\n\
         source {palette_path}\n\n"
	);
	match name {
		"waybar" => format!(
			"{header}\
mkdir -p ~/.config/waybar
set out ~/.config/waybar/colors.css
echo -n > $out

for role in {ROLES}
    set color_name COLOR_$role
    set color $$color_name
    printf \"@define-color %s %s;\\n\" (string lower $role) $color >> $out
    # on-цвет: читаемый текст, когда роль используется как фон
    set on_name \"COLOR_\"$role\"_ON\"
    set on $$on_name
    printf \"@define-color %s_on %s;\\n\" (string lower $role) $on >> $out
end
"
		),
		// swaync импортирует общий ~/.config/colors/colors.css (см. его style.css)
		"swaync" => format!("{header}{SWAYNC}"),
		"kitty" => format!("{header}{KITTY}"),
		"yazi" => format!("{header}{YAZI}"),
		"walker" => format!("{header}{WALKER}"),
		"nvim" => format!("{header}{NVIM}"),
		"btop" => format!("{header}{BTOP}"),
		"niri" => format!("{header}{NIRI}"),
		"fish" => format!("{header}{FISH}"),
		_ => unreachable!(),
	}
}

