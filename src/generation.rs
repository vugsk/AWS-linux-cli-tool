		let mut pal = String::new();
		for role in ROLES.split_whitespace() {
			pal.push_str(&format!("set -gx COLOR_{role} \"#123456\"\n"));
			pal.push_str(&format!("set -gx COLOR_{role}_ON \"#ffffff\"\n"));
		}
		fs::write(cfg.join("colors/palette.fish"), pal).unwrap();

