		let ytheme = fs::read_to_string(cfg.join("yazi/theme.toml")).unwrap();
		assert!(ytheme.contains("dark = \"aswadpftls\""), "yazi: theme.toml не переключён");

		run("nvim");
		let nv = fs::read_to_string(cfg.join("nvim/lua/aswadpftls_palette.lua")).unwrap();
		assert!(nv.trim_start().starts_with("--"), "nvim: нет шапки\n{nv}");
		assert!(nv.contains("return {"), "nvim: нет return-таблицы");
